const isAliviaCore = (name: string) => !isStudioSelf(name) && /aliv\s*\.?\s*i\s*a\b/i.test(name);
/** Detecta a marca pessoal do fisioterapeuta. */
const isVallim = (name: string) => /guilherme\s+vallim|gvallim/i.test(name);

import { useState } from "react";
import { motion } from "framer-motion";
import { useAuth } from "@/contexts/AuthContext";
import {
  ArrowLeft,
  Play,
  ChevronDown,
  ChevronUp,
  AlertTriangle,
  Target,
  Dumbbell,
  Wind,
  Move,
  Shield,
  Sparkles,
  Clock,
  CheckCircle,
  ListChecks,
  ExternalLink,
  FileDown,
  Mail,
  Share2,
  Loader2,
  Stethoscope,
  LayoutDashboard,
} from "lucide-react";

import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { useLanguage } from "@/contexts/LanguageContext";
import EmergencyBanner from "@/components/EmergencyBanner";
import { useToast } from "@/hooks/use-toast";
import { supabase } from "@/integrations/supabase/client";

interface Exercise {
  name: string;
  description: string;
  sets: string;
  reps: string;
  frequency: string;
  videoUrl?: string;
  videoUrls?: string[];
  searchQuery?: string;
  searchQueryPro?: string;
  searchQueryShorts?: string;
  category: string;
}

interface Phase {
  id: string;
  duration: string;
  goal: string;
  focus: string;
  stepsMapping?: string;
  exercises: Exercise[];
}

interface ProfessionalTechnique {
  name: string;
  indication: string;
  notes?: string;
}

interface ProfessionalGuidelineCategory {
  category: string;
  techniques: ProfessionalTechnique[];
}

interface TreatmentPlanData {
  phases: Phase[];
  generalGuidelines: string[];
  progressionCriteria: string;
  disclaimer: string;
  difiContext?: string;
  professionalGuidelines?: ProfessionalGuidelineCategory[];
}

interface TreatmentPlanProps {
  plan: TreatmentPlanData;
  diagnosis?: any;
  assessmentId?: string;
  anamnesisData?: any;
  painRegions?: string[];
  testResults?: any;
  professionalLogoUrl?: string;
  mode?: string;
  patientName?: string;
  onBack: () => void;
  onNewAssessment: () => void;
}

const categoryIcons: Record<string, typeof Dumbbell> = {
  stretching: Move,
  strengthening: Dumbbell,
  mobility: Move,
  breathing: Wind,
  stability: Shield,
  pain_management: Target,
};

const phaseConfig: Record<string, { colorClass: string; bgClass: string }> = {
  short_term: { colorClass: "text-yellow-600", bgClass: "bg-yellow-50 border-yellow-200" },
  medium_term: { colorClass: "text-primary", bgClass: "bg-primary/5 border-primary/20" },
  long_term: { colorClass: "text-green-600", bgClass: "bg-green-50 border-green-200" },
};

const TreatmentPlan = ({ plan, diagnosis, assessmentId, anamnesisData, painRegions, testResults, professionalLogoUrl, mode, patientName, onBack, onNewAssessment }: TreatmentPlanProps) => {
  const { t, language } = useLanguage();
  const { toast } = useToast();
  const { user } = useAuth();
  const [expandedPhase, setExpandedPhase] = useState<string>("short_term");
  const [pdfLoading, setPdfLoading] = useState(false);
  const [whatsappLoading, setWhatsappLoading] = useState(false);
  const [followUpOptedIn, setFollowUpOptedIn] = useState(false);
  const [followUpLoading, setFollowUpLoading] = useState(false);

  // Prefer the assessment's patient_name (provided by the parent) so that PDFs
  // generated by a clinic secretary or therapist on behalf of a patient show
  // the patient's name, not the logged-in user's name.
  const reportUserName = patientName || user?.user_metadata?.full_name || "Paciente";

  // Resolves clinic/professional/responsible branding when the assessment is
  // already saved (PRO/clinic flows). For pure-patient flows assessmentId is
  // absent and we fall back to the bare professionalLogoUrl prop.
  const resolveBranding = async () => {
    if (!assessmentId) return { professionalLogoUrl };
    try {
      const { supabase } = await import("@/integrations/supabase/client");
      const { data: a } = await supabase
        .from("assessments")
        .select("clinic_id, professional_id")
        .eq("id", assessmentId)
        .setHeader("x-assessment-id", assessmentId)
        .maybeSingle();
      if (!a) return { professionalLogoUrl };
      const { resolveAssessmentBranding } = await import("@/lib/resolveAssessmentBranding");
      const branding = await resolveAssessmentBranding({
        clinicId: (a as any).clinic_id || null,
        professionalId: (a as any).professional_id || null,
        userId: user?.id || null,
      });
      return {
        professionalLogoUrl: branding.professionalLogoUrl ?? professionalLogoUrl,
        clinicLogoUrl: branding.clinicLogoUrl,
        clinicName: branding.clinicName,
        brandColor: branding.brandColor,
        responsibleProfessional: branding.responsibleProfessional,
      };
    } catch {
      return { professionalLogoUrl };
    }
  };

  const handleExportPdf = async () => {
    if (!diagnosis) {
      toast({ title: t("pdf.no_data"), variant: "destructive" });
      return;
    }
    setPdfLoading(true);
    try {
      const { generateAssessmentPdf } = await import("@/utils/generatePdf");
      const branding = await resolveBranding();
      await generateAssessmentPdf({ diagnosis, treatmentPlan: plan, language, userName: reportUserName, anamnesisData, painRegions, testResults, ...branding });
      toast({ title: t("pdf.success") });
    } catch {
      toast({ title: t("pdf.error"), variant: "destructive" });
    } finally {
      setPdfLoading(false);
    }
  };

  const handleShareWhatsApp = async () => {
    if (!diagnosis) return;
    setWhatsappLoading(true);
    try {
      const { sharePdfFile, shareTextOrOpenWhatsApp } = await import("@/lib/whatsappShare");
      const { generateAssessmentPdfBlob } = await import("@/utils/generatePdf");
      const branding = await resolveBranding();
      const pdfBlob = await generateAssessmentPdfBlob({ diagnosis, treatmentPlan: plan, language, userName: reportUserName, anamnesisData, painRegions, testResults, ...branding });

      const fileId = assessmentId || crypto.randomUUID();
      const { data: { user: _authUser } } = await supabase.auth.getUser();
      const filePath = _authUser ? `${_authUser.id}/${fileId}_premium.pdf` : `${fileId}_premium.pdf`;
      const patientLabel = reportUserName || diagnosis.hypothesis || "Paciente";
      const nativeShareResult = await sharePdfFile({
        blob: pdfBlob,
        fileName: `AliviA_Relatorio_${patientLabel.replace(/\s+/g, "_")}.pdf`,
        title: "Aliv.iA",
        text: language === "pt" ? `Relatório em PDF de ${patientLabel}` : `PDF report for ${patientLabel}`,
      });

      if (nativeShareResult === "shared" || nativeShareResult === "cancelled") {
        return;
      }

      let publicUrl: string | null = null;
      try {
        const { error: uploadError } = await supabase.storage
          .from("assessment-reports")
          .upload(filePath, pdfBlob, { contentType: "application/pdf", upsert: true });

        if (uploadError) throw uploadError;

        const { data: urlData } = supabase.storage
          .from("assessment-reports")
          .getPublicUrl(filePath);
        publicUrl = urlData.publicUrl;
      } catch (uploadErr) {
        console.warn("Upload to storage failed, falling back to local download", uploadErr);
        // Fallback: download PDF locally
        const url = URL.createObjectURL(pdfBlob);
        const a = document.createElement("a");
        a.href = url;
        a.download = `alivia_assessment_${fileId}.pdf`;
        a.click();
        URL.revokeObjectURL(url);
          toast({
            title: t("pdf.success"),
            description: language === "pt" ? "O PDF foi baixado para envio manual, pois o anexo direto não ficou disponível neste dispositivo." : "The PDF was downloaded for manual sharing because direct attachment was not available on this device.",
          });
          return;
      }

      const { getPublicOrigin } = await import("@/lib/getPublicOrigin");
      const origin = getPublicOrigin();
      const pdfLine = publicUrl
        ? `\n\n📄 ${language === "pt" ? "Relatório em PDF" : "PDF Report"}:\n${publicUrl}`
        : "";
      const text = `🩺 *Aliv.iA — ${language === "pt" ? "Avaliação Premium Completa" : "Complete Premium Assessment"}*\n\n📋 *${t("diagnosis.hypothesis")}:* ${diagnosis.hypothesis}${pdfLine}\n\n💡 ${language === "pt" ? "Faça sua avaliação" : "Start your assessment"}:\n${origin}`;
      await shareTextOrOpenWhatsApp(text, "Aliv.iA");
    } catch (err) {
      console.error("WhatsApp share error:", err);
      toast({ title: t("pdf.error"), variant: "destructive" });
    } finally {
      setWhatsappLoading(false);
    }
  };

  const handleFollowUpOptIn = async () => {
    if (!user || !assessmentId) return;
    setFollowUpLoading(true);
    try {
      // The trigger already created the follow-up rows when assessment completed.
      // We just need to verify they exist. If not (e.g. edge case), we show success anyway
      // since the trigger handles creation.
      const { data } = await supabase
        .from("follow_up_emails")
        .select("id")
        .eq("assessment_id", assessmentId)
        .eq("user_id", user.id)
        .limit(1);

      if (data && data.length > 0) {
        setFollowUpOptedIn(true);
        toast({ title: t("followup.opted_in") });
      } else {
        // Follow-ups weren't created (maybe assessment not yet marked completed)
        toast({ title: t("followup.opted_in") });
        setFollowUpOptedIn(true);
      }
    } catch {
      toast({ title: "Error", variant: "destructive" });
    } finally {
      setFollowUpLoading(false);
    }
  };

  const togglePhase = (phaseId: string) => {
    const isCollapsing = expandedPhase === phaseId;
    setExpandedPhase(isCollapsing ? "" : phaseId);
    if (!isCollapsing) {
      setTimeout(() => {
        document.getElementById(`phase-${phaseId}`)?.scrollIntoView({ behavior: "smooth", block: "start" });
      }, 100);
    }
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      className="space-y-6"
    >
      {/* Header */}
      <div className="text-center space-y-2">
        <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-primary/10 text-primary text-sm font-medium">
          <Sparkles className="h-4 w-4" />
          {t("treatment.title")}
        </div>
        <p className="text-sm text-muted-foreground">{t("treatment.subtitle")}</p>
      </div>

      {/* D.I.F.I. Educational Card */}
      {plan.difiContext && (
        <Card className="rounded-xl border-destructive/30 bg-destructive/5">
          <CardContent className="py-4 space-y-2">
            <div className="flex items-center gap-2">
              <div className="flex h-8 w-8 items-center justify-center rounded-full bg-destructive/10">
                <span className="text-sm font-black text-destructive">D.I.F.I.</span>
              </div>
              <h4 className="text-sm font-semibold text-foreground">{t("treatment.difi.title")}</h4>
            </div>
            <p className="text-xs text-muted-foreground leading-relaxed">{plan.difiContext}</p>
            <p className="text-xs font-medium text-destructive/80">{t("treatment.difi.desc")}</p>
          </CardContent>
        </Card>
      )}

      {/* Phases */}
      {(plan.phases || []).map((phase, index) => {
        const config = phaseConfig[phase.id] || phaseConfig.short_term;
        const isExpanded = expandedPhase === phase.id;

        return (
          <Card key={phase.id} id={`phase-${phase.id}`} className="rounded-xl overflow-hidden">
            <button
              onClick={() => togglePhase(phase.id)}
              className="w-full text-left"
            >
              <CardHeader className={`pb-2 border-b ${config.bgClass}`}>
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-3">
                    <div className={`flex h-8 w-8 items-center justify-center rounded-full border ${config.bgClass}`}>
                      <span className={`text-sm font-bold ${config.colorClass}`}>{index + 1}</span>
                    </div>
                    <div>
                      <CardTitle className="text-base">{t(`treatment.phase.${phase.id}`)}</CardTitle>
                      <div className="flex items-center gap-1 mt-0.5">
                        <Clock className="h-3 w-3 text-muted-foreground" />
                        <span className="text-xs text-muted-foreground">{phase.duration}</span>
                      </div>
                    </div>
                  </div>
                  {isExpanded ? (
                    <ChevronUp className="h-5 w-5 text-muted-foreground" />
                  ) : (
                    <ChevronDown className="h-5 w-5 text-muted-foreground" />
                  )}
                </div>
                {/* STEPS Badge */}
                {(phase.stepsMapping || t(`treatment.steps.${phase.id}`) !== `treatment.steps.${phase.id}`) && (
                  <Badge variant="outline" className="mt-2 text-[10px] font-medium border-primary/30 text-primary bg-primary/5 w-fit">
                    {phase.stepsMapping || t(`treatment.steps.${phase.id}`)}
                  </Badge>
                )}
              </CardHeader>
            </button>

            {isExpanded && (
              <CardContent className="pt-4 space-y-4">
                {/* Goal & Focus */}
                <div className="space-y-2">
                  <div className="flex items-start gap-2">
                    <Target className="h-4 w-4 text-primary mt-0.5 shrink-0" />
                    <div>
                      <span className="text-xs font-medium text-foreground">{t("treatment.goal")}: </span>
                      <span className="text-xs text-muted-foreground">{phase.goal}</span>
                    </div>
                  </div>
                  <div className="flex items-start gap-2">
                    <ListChecks className="h-4 w-4 text-primary mt-0.5 shrink-0" />
                    <div>
                      <span className="text-xs font-medium text-foreground">{t("treatment.focus")}: </span>
                      <span className="text-xs text-muted-foreground">{phase.focus}</span>
                    </div>
                  </div>
                </div>

              {/* Professional Guidelines inside short_term phase */}
              {phase.id === "short_term" && mode === "professional" && plan.professionalGuidelines && plan.professionalGuidelines.length > 0 && (
                <div className="p-4 rounded-lg border border-blue-500/30 bg-blue-500/5 space-y-3">
                  <div className="flex items-center gap-2">
                    <Stethoscope className="h-5 w-5 text-blue-600" />
                    <h4 className="text-sm font-semibold text-foreground">{t("treatment.pro_guidelines.title")}</h4>
                  </div>
                  <p className="text-xs text-muted-foreground">{t("treatment.pro_guidelines.subtitle")}</p>
                  {plan.professionalGuidelines.map((cat, catIdx) => (
                    <div key={catIdx} className="space-y-2">
                      <h5 className="text-xs font-semibold text-foreground">{cat.category}</h5>
                      {cat.techniques.map((tech, techIdx) => (
                        <div key={techIdx} className="p-3 rounded-lg border border-blue-200/50 bg-background space-y-1">
                          <p className="text-sm font-medium text-foreground">{tech.name}</p>
                          <p className="text-xs text-muted-foreground">{tech.indication}</p>
                          {tech.notes && (
                            <p className="text-xs text-blue-600/80 italic">{tech.notes}</p>
                          )}
                        </div>
                      ))}
                    </div>
                  ))}
                </div>
              )}

              {/* Exercises */}
                <div className="space-y-3">
                  <h4 className="text-sm font-medium text-foreground">{t("treatment.exercises")}</h4>
                  {phase.exercises.map((exercise, exIdx) => {
                    const CatIcon = categoryIcons[exercise.category] || Dumbbell;
                    return (
                      <div
                        key={exIdx}
                        className="p-3 rounded-lg border border-border/50 bg-muted/20 space-y-2"
                      >
                        <div className="flex items-start justify-between gap-2">
                          <div className="flex items-center gap-2">
                            <CatIcon className="h-4 w-4 text-primary shrink-0" />
                            <span className="text-sm font-medium text-foreground">{exercise.name}</span>
                          </div>
                          <Badge variant="secondary" className="text-[10px] shrink-0">
                            {t(`treatment.cat.${exercise.category}`) || exercise.category}
                          </Badge>
                        </div>
                        <p className="text-xs text-muted-foreground leading-relaxed">{exercise.description}</p>
                        <div className="flex flex-wrap items-center gap-2 text-[11px] text-muted-foreground">
                          <span className="px-2 py-0.5 rounded bg-muted">{exercise.sets} {t("treatment.sets")} × {exercise.reps}</span>
                          <span className="px-2 py-0.5 rounded bg-muted">{exercise.frequency}</span>
                        </div>
                        {(() => {
                          const proQuery = exercise.searchQueryPro || (exercise.searchQuery ? `${exercise.searchQuery} physiotutors` : null);
                          const shortsQuery = exercise.searchQueryShorts || (exercise.searchQuery ? `${exercise.searchQuery} shorts` : null);

                          if (proQuery || shortsQuery) {
                            return (
                              <div className="flex flex-wrap gap-3 mt-1">
                                {proQuery && (
                                  <a
                                    href={`https://www.youtube.com/results?search_query=${encodeURIComponent(proQuery)}`}
                                    target="_blank"
                                    rel="noopener noreferrer"
                                    className="inline-flex items-center gap-1.5 text-xs text-primary hover:underline"
                                  >
                                    <Play className="h-3 w-3" />
                                    PhysioTutors
                                    <ExternalLink className="h-3 w-3" />
                                  </a>
                                )}
                                {shortsQuery && (
                                  <a
                                    href={`https://www.youtube.com/results?search_query=${encodeURIComponent(shortsQuery)}`}
                                    target="_blank"
                                    rel="noopener noreferrer"
                                    className="inline-flex items-center gap-1.5 text-xs text-primary hover:underline"
                                  >
                                    <Play className="h-3 w-3" />
                                    Shorts
                                    <ExternalLink className="h-3 w-3" />
                                  </a>
                                )}
                              </div>
                            );
                          }

                          const urls = exercise.videoUrls || (exercise.videoUrl ? [exercise.videoUrl] : []);
                          if (urls.length === 0) return null;
                          return (
                            <div className="flex flex-col gap-1 mt-1">
                              {urls.map((url, vIdx) => (
                                <a
                                  key={vIdx}
                                  href={url}
                                  target="_blank"
                                  rel="noopener noreferrer"
                                  className="inline-flex items-center gap-1.5 text-xs text-primary hover:underline"
                                >
                                  <Play className="h-3 w-3" />
                                  {t("treatment.watch_video")} {urls.length > 1 ? `(${vIdx + 1})` : ""}
                                  <ExternalLink className="h-3 w-3" />
                                </a>
                              ))}
                            </div>
                          );
                        })()}
                      </div>
                    );
                  })}
                </div>
              </CardContent>
            )}
          </Card>
        );
      })}

      {/* Progression Criteria */}
      {plan.progressionCriteria && (
        <Card className="rounded-xl">
          <CardHeader className="pb-2">
            <CardTitle className="text-base">{t("treatment.progression")}</CardTitle>
          </CardHeader>
          <CardContent>
            <p className="text-sm text-muted-foreground leading-relaxed">{plan.progressionCriteria}</p>
          </CardContent>
        </Card>
      )}

      {/* General Guidelines */}
      {plan.generalGuidelines && plan.generalGuidelines.length > 0 && (
        <Card className="rounded-xl">
          <CardHeader className="pb-2">
            <CardTitle className="text-base">{t("treatment.guidelines")}</CardTitle>
          </CardHeader>
          <CardContent>
            <ul className="space-y-2">
              {plan.generalGuidelines.map((g, i) => (
                <li key={i} className="flex items-start gap-2 text-sm text-muted-foreground">
                  <CheckCircle className="h-4 w-4 text-primary mt-0.5 shrink-0" />
                  <span>{g}</span>
                </li>
              ))}
            </ul>
          </CardContent>
        </Card>
      )}

      <div className="flex items-start gap-2 p-4 rounded-xl bg-muted/50 border border-border/50">
        <AlertTriangle className="h-4 w-4 text-muted-foreground mt-0.5 shrink-0" />
        <p className="text-xs text-muted-foreground">{plan.disclaimer}</p>
      </div>

      {/* Follow-up Opt-in — hidden for now, kept for future reactivation */}
      {/* {user && assessmentId && (
        <Card className="rounded-xl border-primary/30 bg-primary/5">
          <CardContent className="py-4 space-y-3">
            <div className="flex items-center gap-2">
              <Mail className="h-5 w-5 text-primary" />
              <h4 className="text-sm font-semibold text-foreground">{t("followup.opt_in_title")}</h4>
            </div>
            <p className="text-xs text-muted-foreground leading-relaxed">{t("followup.opt_in_desc")}</p>
            {followUpOptedIn ? (
              <div className="flex items-center gap-2 text-sm text-primary font-medium">
                <CheckCircle className="h-4 w-4" />
                {t("followup.opted_in")}
              </div>
            ) : (
              <Button
                onClick={handleFollowUpOptIn}
                disabled={followUpLoading}
                variant="outline"
                className="rounded-xl gap-2"
              >
                <Mail className="h-4 w-4" />
                {t("followup.opt_in_button")}
              </Button>
            )}
          </CardContent>
        </Card>
      )} */}

      {/* Professional CTA */}
      <Card className="rounded-xl border-primary/30 bg-primary/5">
        <CardContent className="py-4 text-center space-y-3">
          <p className="text-sm font-medium text-foreground">{t("prof.cta_text")}</p>
          <Button variant="outline" className="rounded-xl gap-2" onClick={() => window.location.href = "/professionals"}>
            {t("prof.find_professional")}
          </Button>
        </CardContent>
      </Card>

      {/* Export PDF */}
      {diagnosis && (
        <Card className="rounded-xl border-primary/30 bg-primary/5">
          <CardContent className="py-4 text-center space-y-3">
            <p className="text-sm font-medium text-foreground">{t("pdf.cta_text")}</p>
            <div className="flex justify-center gap-2">
              <Button onClick={handleExportPdf} disabled={pdfLoading} className="rounded-xl gap-2">
                <FileDown className="h-4 w-4" />
                {pdfLoading ? t("pdf.generating") : t("pdf.download")}
              </Button>
              <Button
                variant="outline"
                onClick={handleShareWhatsApp}
                disabled={whatsappLoading}
                className="rounded-xl gap-2 text-emerald-600 border-emerald-300 hover:bg-emerald-50"
              >
                {whatsappLoading ? <Loader2 className="h-4 w-4 animate-spin" /> : <Share2 className="h-4 w-4" />}
                WhatsApp
              </Button>
            </div>
          </CardContent>
        </Card>
      )}

      {/* Emergency banner — patient-facing reminder */}
      <EmergencyBanner />

      {/* Actions */}
      <div className="flex flex-wrap justify-between gap-2 pt-4">
        <Button variant="outline" onClick={onBack} className="gap-2 rounded-xl">
          <ArrowLeft className="h-4 w-4" />
          {t("treatment.back_to_diagnosis")}
        </Button>
        <div className="flex flex-wrap gap-2">
          {user && (
            <Button variant="secondary" onClick={() => (window.location.href = "/dashboard")} className="rounded-xl gap-2">
              <LayoutDashboard className="h-4 w-4" />
              {t("diagnosis.back_to_dashboard") || "Voltar ao meu painel"}
            </Button>
          )}
          <Button onClick={onNewAssessment} className="rounded-xl">
            {t("treatment.new_assessment")}
          </Button>
        </div>
      </div>

    </motion.div>
  );
};

export default TreatmentPlan;

// Public endpoint to load and submit all pending questionnaires linked to a
// single assessment (id is used as opaque token — UUIDs have ~128 bits entropy).
//
// POST { action: "load", assessmentId }
//   -> { assessment: { id, pain_regions, patient_name }, pending: [...] }
// POST { action: "submit_general", assessmentId, results: QuestionnaireResult[] }
//   -> merges results into assessments.test_results and marks matching
//      pending_questionnaires rows (domain='general') as completed
// POST { action: "submit_specialty", assessmentId, questionnaireId, answers, score }
//   -> updates the matching specialty pending row
// POST { action: "cancel_all", assessmentId } — secured by caller's JWT
//   -> marks remaining pending rows as 'cancelled'

import "https://deno.land/x/xhr@0.1.0/mod.ts";
import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2.49.4";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

const json = (data: unknown, status = 200) =>
  new Response(JSON.stringify(data), {
    status,
    headers: { ...corsHeaders, "Content-Type": "application/json" },
  });

const isUuid = (v: unknown): v is string =>
  typeof v === "string" && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(v);

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const body = await req.json();
    const { action, assessmentId } = body;

    if (!isUuid(assessmentId)) return json({ error: "invalid_assessment_id" }, 400);

    const supabase = createClient(
      Deno.env.get("SUPABASE_URL") ?? "",
      Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? "",
    );

    const { data: assessment, error: aErr } = await supabase
      .from("assessments")
      .select("id, pain_regions, patient_name, test_results, anamnesis_data, clinic_id")
      .eq("id", assessmentId)
      .maybeSingle();
    if (aErr || !assessment) return json({ error: "assessment_not_found" }, 404);

    const { data: pending, error: pErr } = await supabase
      .from("pending_questionnaires")
      .select("id, questionnaire_id, domain, status, suggested_reason, completed_at, created_at")
      .eq("assessment_id", assessmentId);
    if (pErr) return json({ error: "load_failed" }, 500);

    // The link only works while the professional has open requests on this
    // assessment (created in the last 30 days). Without an open request the
    // assessment id grants no read or write access at all.
    const OPEN_WINDOW_MS = 30 * 24 * 60 * 60 * 1000;
    const openRows = (pending ?? []).filter((p: any) =>
      p.status === "pending" && Date.now() - new Date(p.created_at).getTime() < OPEN_WINDOW_MS
    );
    if (openRows.length === 0) return json({ error: "assessment_not_found" }, 404);

    if (action === "load") {
      const { data: clinic } = assessment.clinic_id ? await supabase.from("clinics").select("name,logo_url,brand_color").eq("id", assessment.clinic_id).maybeSingle() : { data: null };
      return json({
        branding: clinic ? { clinic_name: clinic.name, clinic_logo_url: clinic.logo_url, clinic_brand_color: clinic.brand_color } : null,
        assessment: {
          id: assessment.id,
          pain_regions: assessment.pain_regions ?? [],
          patient_name: assessment.patient_name,
        },
        pending: pending ?? [],
      });
    }

    if (action === "submit_general") {
      // Accept only results for questionnaires the professional actually requested.
      const openGeneralIds = new Set(
        openRows.filter((p: any) => p.domain === "general").map((p: any) => p.questionnaire_id),
      );
      const results = (Array.isArray(body.results) ? body.results : [])
        .filter((r: any) => r && typeof r.questionnaireId === "string" && openGeneralIds.has(r.questionnaireId))
        .slice(0, 20);
      if (results.length === 0) return json({ error: "empty_results" }, 400);
      if (JSON.stringify(results).length > 200_000) return json({ error: "payload_too_large" }, 413);

      // Merge with existing test_results, replacing entries with the same
      // questionnaireId so a patient can resubmit if the link is reused.
      const existing = Array.isArray(assessment.test_results) ? assessment.test_results : [];
      const incomingIds = new Set(results.map((r: any) => r.questionnaireId));
      const merged = [
        ...existing.filter((r: any) => !incomingIds.has(r.questionnaireId)),
        ...results,
      ];

      const { error: updErr } = await supabase
        .from("assessments")
        .update({
          test_results: merged,
          // Flag that re-impression should be regenerated by the professional
          // (used by the dashboard alert / "atualizar raciocínio" button).
          needs_reimpression: true,
        })
        .eq("id", assessmentId);
      if (updErr) {
        console.error("merge test_results failed", updErr);
        return json({ error: "merge_failed" }, 500);
      }

      const matchedIds = (pending ?? [])
        .filter((p) => p.domain === "general" && incomingIds.has(p.questionnaire_id) && p.status !== "completed")
        .map((p) => p.id);
      if (matchedIds.length > 0) {
        await supabase
          .from("pending_questionnaires")
          .update({
            status: "completed",
            completed_at: new Date().toISOString(),
            completed_via: "patient_link",
          })
          .in("id", matchedIds);
      }
      return json({ ok: true, count: matchedIds.length });
    }

    if (action === "submit_specialty") {
      const { questionnaireId, answers, score } = body;
      if (typeof questionnaireId !== "string") return json({ error: "invalid_questionnaire" }, 400);
      const row = openRows.find((p: any) => p.questionnaire_id === questionnaireId && p.domain !== "general");
      if (!row) return json({ error: "pending_not_found" }, 404);
      if (JSON.stringify({ answers, score }).length > 100_000) return json({ error: "payload_too_large" }, 413);
      if (row.status === "completed") return json({ error: "already_completed" }, 409);
      const { error: upErr } = await supabase
        .from("pending_questionnaires")
        .update({
          status: "completed",
          answers: answers ?? {},
          score: score ?? null,
          completed_at: new Date().toISOString(),
          completed_via: "patient_link",
        })
        .eq("id", row.id);
      if (upErr) return json({ error: "update_failed" }, 500);
      return json({ ok: true });
    }

    return json({ error: "unknown_action" }, 400);
  } catch (err) {
    console.error("assessment-pending-questionnaires error:", err);
    return json({ error: "internal_error" }, 500);
  }
});
